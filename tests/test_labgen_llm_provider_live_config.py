def _make_live_adapter(candidate: dict = None) -> OpenAICompatibleLLMProviderAdapter:
    """Build a live adapter with a fake HTTP client that returns a valid candidate."""
    mock_client = MagicMock()
    body = {
        "choices": [
            {
                "message": {"content": json.dumps(candidate or _VALID_CANDIDATE)},
                "finish_reason": "stop",
            }
        ]
    }
    mock_client.post.return_value = MagicMock(status_code=200, **{"json.return_value": body})
    return OpenAICompatibleLLMProviderAdapter(
        config=OpenAICompatibleProviderConfig(
            base_url="https://api.example.com/v1",
            model="test-model",
        ),
        api_key="sk-fake-key-for-testing-only",
        http_client=mock_client,
    )


def _make_app_with_svc(svc: LLMProviderBoundaryService, *, as_admin: bool = True):
    from contextlib import contextmanager
    from backend.main import app

    @contextmanager
    def _ctx():
        saved = dict(app.dependency_overrides)
        try:
            if as_admin:
                app.dependency_overrides[require_admin_user] = lambda: "admin"
                app.dependency_overrides[get_current_user] = lambda: "admin"
            else:
                app.dependency_overrides[get_current_user] = lambda: "student"
            app.dependency_overrides[get_llm_provider_service] = lambda: svc
            yield TestClient(app)
        finally:
            app.dependency_overrides.clear()
            app.dependency_overrides.update(saved)

    return _ctx()


