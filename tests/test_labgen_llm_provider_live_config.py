class TestGenerationServiceLiveMode:
    def _make_generation_service(self, live_adapter=None):
        from backend.labgen.llm_generation import (
            FakeDraftGenerationAdapter,
            LabDraftGenerationService,
        )
        from backend.labgen.repository import LabDraftRepository
        from backend.labgen.static_validator import StaticValidator

        repo = LabDraftRepository.__new__(LabDraftRepository)
        repo._path = None
        created = []

        def _create(draft):
            created.append(draft)
            return draft

        repo.create = _create
        repo.list = lambda: []

        svc = LLMProviderBoundaryService(
            config=LLMProviderConfig(mode=LLMProviderMode.LIVE_ENABLED),
            live_adapter=live_adapter,
        )
        return LabDraftGenerationService(
            port=FakeDraftGenerationAdapter(),
            validator=StaticValidator(),
            repo=repo,
            provider_boundary=svc,
        ), created

    def test_live_mode_valid_response_creates_draft(self):
        from backend.labgen.llm_generation import LabDraftGenerationRequest

        adapter = _make_live_adapter()
        gen_svc, created = self._make_generation_service(live_adapter=adapter)
        req = LabDraftGenerationRequest(
            user_prompt="k8s networking lab",
            requester_user_id="admin",
        )
        draft, _, warnings, _ = gen_svc.generate_and_create(req)
        assert draft is not None
        assert len(created) == 1

    def test_live_mode_provider_candidate_publish_status_never_published(self):
        from backend.labgen.llm_generation import LabDraftGenerationRequest
        from backend.labgen.models import PublishStatus

        adapter = _make_live_adapter(
            candidate={**_VALID_CANDIDATE, "publish_status": "published"}
        )
        gen_svc, created = self._make_generation_service(live_adapter=adapter)
        req = LabDraftGenerationRequest(
            user_prompt="k8s lab",
            requester_user_id="admin",
        )
        draft, _, _, _ = gen_svc.generate_and_create(req)
        assert draft.publish_status != PublishStatus.PUBLISHED

    def test_live_mode_provider_failure_does_not_create_draft(self):
        from backend.labgen.llm_generation import (
            DraftGenerationRejected,
            LabDraftGenerationRequest,
        )

        # Adapter with no live_adapter → config_error → rejected_reason
        gen_svc, created = self._make_generation_service(live_adapter=None)
        req = LabDraftGenerationRequest(
            user_prompt="k8s lab",
            requester_user_id="admin",
        )
        with pytest.raises(DraftGenerationRejected):
            gen_svc.generate_and_create(req)
        assert len(created) == 0

    def test_default_fake_path_unchanged_when_no_live_adapter(self):
        from backend.labgen.llm_generation import (
            FakeDraftGenerationAdapter,
            LabDraftGenerationRequest,
            LabDraftGenerationService,
        )
        from backend.labgen.repository import LabDraftRepository
        from backend.labgen.static_validator import StaticValidator

        repo = LabDraftRepository.__new__(LabDraftRepository)
        repo._path = None
        created = []
        repo.create = lambda d: created.append(d) or d
        repo.list = lambda: []

        svc = LLMProviderBoundaryService(
            config=LLMProviderConfig(mode=LLMProviderMode.FAKE_ONLY),
        )
        gen_svc = LabDraftGenerationService(
            port=FakeDraftGenerationAdapter(),
            validator=StaticValidator(),
            repo=repo,
            provider_boundary=svc,
        )
        req = LabDraftGenerationRequest(
            user_prompt="regression test",
            requester_user_id="admin",
        )
        draft, _, _, _ = gen_svc.generate_and_create(req)
        assert draft is not None


