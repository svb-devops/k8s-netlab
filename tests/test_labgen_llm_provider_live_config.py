class TestLiveModeSwitching:
    def test_fake_only_is_default(self):
        svc = LLMProviderBoundaryService.create_from_env()
        assert svc.config.mode == LLMProviderMode.FAKE_ONLY
        assert svc.live_enabled is False

    def test_live_enabled_false_when_no_live_adapter(self):
        svc = LLMProviderBoundaryService(
            config=LLMProviderConfig(mode=LLMProviderMode.LIVE_ENABLED),
            live_adapter=None,
        )
        assert svc.live_enabled is False

    def test_live_enabled_true_when_adapter_present(self):
        adapter = _make_live_adapter()
        svc = LLMProviderBoundaryService(
            config=LLMProviderConfig(mode=LLMProviderMode.LIVE_ENABLED),
            live_adapter=adapter,
        )
        assert svc.live_enabled is True

    def test_live_enabled_returns_config_error_when_adapter_none(self):
        svc = LLMProviderBoundaryService(
            config=LLMProviderConfig(mode=LLMProviderMode.LIVE_ENABLED),
            live_adapter=None,
        )
        req = LLMProviderRequest(
            purpose="draft_generation",
            sanitized_user_prompt="test",
        )
        resp = svc.call(req)
        assert resp.rejected_reason == "live_provider_config_error"

    def test_live_enabled_with_valid_adapter_returns_candidate(self):
        adapter = _make_live_adapter()
        svc = LLMProviderBoundaryService(
            config=LLMProviderConfig(mode=LLMProviderMode.LIVE_ENABLED),
            live_adapter=adapter,
        )
        req = LLMProviderRequest(
            purpose="draft_generation",
            sanitized_user_prompt="deploy a pod and verify networking",
        )
        resp = svc.call(req)
        assert resp.rejected_reason is None
        assert resp.candidate_json is not None
        assert resp.candidate_json.get("title") == "Live LLM Test Lab"

    def test_safety_policy_live_enabled_when_adapter_active(self):
        adapter = _make_live_adapter()
        svc = LLMProviderBoundaryService(
            config=LLMProviderConfig(mode=LLMProviderMode.LIVE_ENABLED),
            live_adapter=adapter,
        )
        assert svc.safety_policy.live_providers_enabled is True

    def test_safety_policy_live_disabled_when_no_adapter(self):
        svc = LLMProviderBoundaryService(
            config=LLMProviderConfig(mode=LLMProviderMode.FAKE_ONLY),
        )
        assert svc.safety_policy.live_providers_enabled is False


