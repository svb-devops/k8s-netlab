class TestValidateConfigEndpoint:
    def _client(self):
        from contextlib import contextmanager
        from backend.main import app

        @contextmanager
        def _ctx():
            saved = dict(app.dependency_overrides)
            try:
                app.dependency_overrides[require_admin_user] = lambda: "admin"
                app.dependency_overrides[get_current_user] = lambda: "admin"
                yield TestClient(app)
            finally:
                app.dependency_overrides.clear()
                app.dependency_overrides.update(saved)

        return _ctx()

    def test_admin_can_validate(self):
        with self._client() as client:
            r = client.post("/api/labgen/llm-provider/validate-config")
        assert r.status_code == 200

    def test_non_admin_forbidden(self):
        from backend.main import app
        saved = dict(app.dependency_overrides)
        try:
            app.dependency_overrides[get_current_user] = lambda: "student"
            client = TestClient(app)
            r = client.post("/api/labgen/llm-provider/validate-config")
        finally:
            app.dependency_overrides.clear()
            app.dependency_overrides.update(saved)
        assert r.status_code == 403

    def test_response_has_valid_and_config_issues(self):
        with self._client() as client:
            r = client.post("/api/labgen/llm-provider/validate-config")
        body = r.json()
        assert "valid" in body
        assert "config_issues" in body

    def test_response_never_contains_api_key(self):
        with self._client() as client:
            r = client.post("/api/labgen/llm-provider/validate-config")
        assert "sk-" not in r.text
        assert "api_key" not in r.text.lower() or '"api_key"' not in r.text


